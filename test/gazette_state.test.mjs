test('new events are detected from compact summaries and arcade scores are capped', () => {
  const state=blank(), first=gazetteSummary(state);
  state.pets.push({id:'mabel',bond:0}); state.mayhem.curios['monkey-paw']=1; state.mayhem.coffins=1;
  state.arcade.best.stack=900; state.collections.claimed.push('set-one'); state.almanac.chapters={issue:{claimed:2}};
  state.courtroom={episodes:1,last:'stolen-sock'};
  const second=gazetteSummary(state), changes=gazetteChanges(first,second);
  assert.deepEqual(changes.map(x=>x.kind),['adopted','coffin','verdict','arcade_best','collection','almanac']);
  assert.equal(changes.find(x=>x.kind==='arcade_best').data.score,500);
  state.pets[0].bond=12;
  assert.deepEqual(gazetteChanges(second,gazetteSummary(state)).map(x=>x.data.level),[5,10]);
  assert.deepEqual(gazetteChanges(second,second),[]);
});
