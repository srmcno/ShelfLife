test('a fresh device refreshes sharing before recording new news and rebaselines on reconnect', async () => {
  const fake=createFakeSupabase();
  const storage=()=>{const items=new Map();return {getItem:k=>items.get(k)||null,setItem:(k,v)=>items.set(k,String(v)),removeItem:k=>items.delete(k)};};
  const firstStorage=storage(), secondStorage=storage();
  const deviceA=createCloud({config:fake.config,fetch:fake.fetch,storage:firstStorage});
  await deviceA.signInAnonymously();
  await deviceA.rpc('gazette_set_sharing',{p_on:false}); await deviceA.rpc('gazette_set_sharing',{p_on:true});
  secondStorage.setItem('shelflife.cloud',JSON.stringify({session:deviceA.session()}));
  const deviceB=createCloud({config:fake.config,fetch:fake.fetch,storage:secondStorage});
  const state=blank(); state.pets.push({id:'old-household',bond:0}); let serial=0;
  const journal=createGazetteJournal({cloud:deviceB,getState:()=>state,storage:secondStorage,keygen:()=>`00000000-0000-4000-8000-${String(++serial).padStart(12,'0')}`});
  await journal.refreshSettings();
  journal.capture(); assert.equal(journal.queued().length,0,'existing residents establish a baseline');
  state.pets.push({id:'first-new',bond:0}); journal.capture(); assert.equal(journal.queued()[0].generation,2);
  await journal.flush(); assert.deepEqual((await deviceA.rpc('gazette_feed')).events.map(e=>e.data.resident),['first-new']);
  await deviceA.rpc('gazette_set_sharing',{p_on:false});
  state.pets.push({id:'while-offline',bond:0}); journal.capture();
  await deviceA.rpc('gazette_set_sharing',{p_on:true});
  await journal.refreshSettings(); assert.equal(journal.queued().length,0,'reconnect clears unknown-interval news');
  state.pets.push({id:'after-reconnect',bond:0}); journal.capture(); assert.equal(journal.queued()[0].generation,4);
  await journal.flush();
  const residents=(await deviceA.rpc('gazette_feed')).events.map(e=>e.data.resident);
  assert.ok(residents.includes('first-new')); assert.ok(residents.includes('after-reconnect')); assert.ok(!residents.includes('while-offline'));
});
test('actual coffin, Court, collection and Almanac operations produce their corresponding news', () => {
  const now = new Date(2026, 9, 5, 14).getTime(), state = blankState();
  state.pets = ['g0','g1','g2'].map((id,i) => ({id,name:['Agnes','Pip','Oswald'][i],traits:[],needs:{food:50,fuss:50,clean:50},bond:3,cared:0,grudges:0,born:now-86400000}));
  state.pets.forEach((p,i)=>{state.slots[i]=p.id;});
  state.mayhem.souls=1000;
  let before=gazetteSummary(state);
  const drop=openCoffin(state,now,()=>0.999);
  assert.ok(drop && ['rare','cursed','unholy'].includes(drop.curio.rarity));
  assert.ok(gazetteChanges(before,gazetteSummary(state)).some(e=>e.kind==='coffin' && e.data.item===drop.curio.id));
  const ep=castEpisode(state,{caseId:COURT_CASES[0].id,plaintiffId:'g0',defendantId:'g1'},seededRandom(3));
  episodeRule(ep,'plaintiff',seededRandom(4)); before=gazetteSummary(state); assert.ok(courtFinish(state,ep,now));
  assert.ok(gazetteChanges(before,gazetteSummary(state)).some(e=>e.kind==='verdict' && e.data.item===COURT_CASES[0].id));
  for (const id of ['damp-receipt','condolence-card','name-tag','map-house','named-book']) state.mayhem.curios[id]=1;
  before=gazetteSummary(state); assert.ok(claimSet(state,'paper'));
  assert.ok(gazetteChanges(before,gazetteSummary(state)).some(e=>e.kind==='collection' && e.data.item==='paper'));
  syncAlmanac(state,now); grantXp(state,5000,now); before=gazetteSummary(state);
  assert.ok(claimTier(state,chapterAt(now),1,now));
  assert.ok(gazetteChanges(before,gazetteSummary(state)).some(e=>e.kind==='almanac' && e.data.tier===1));
});
